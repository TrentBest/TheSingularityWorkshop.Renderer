using System.Security;
using System.Text;
using TheSingularityWorkshop.Renderer;

var outputPath = args.Length > 0
    ? Path.GetFullPath(args[0])
    : Path.GetFullPath("docs/assets/living-event-horizons.svg");

var examples = new[]
{
    (Name: "Landmark identity", Target: RepresentationTarget.Semantic, X: 110),
    (Name: "Environmental mass", Target: RepresentationTarget.Aggregate, X: 305),
    (Name: "Distant presence", Target: RepresentationTarget.Distant, X: 500),
    (Name: "Near detail", Target: RepresentationTarget.Near, X: 695),
    (Name: "Interactive detail", Target: RepresentationTarget.Interactive, X: 890)
};

var results = new List<(string Name, RepresentationTarget Target, int X, RepresentationTarget Active)>();

foreach (var example in examples)
{
    var context = new RendererComputationContext(
        $"living-docs-{example.Target}",
        example.Target);

    using var machine = new RendererComputationMachine(context);
    var active = machine.Advance();
    results.Add((example.Name, example.Target, example.X, active));
}

var svg = new StringBuilder();
svg.AppendLine("""<?xml version="1.0" encoding="UTF-8"?>""");
svg.AppendLine("""<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="360" viewBox="0 0 1000 360" role="img" aria-labelledby="title desc">""");
svg.AppendLine("""  <title id="title">Living Event Horizons — FSM_API representation states</title>""");
svg.AppendLine("""  <desc id="desc">A generated snapshot of five RendererComputationMachine instances after FSM_API advances each instance into its requested representation. The SVG adds presentation-only motion to the resulting state markers.</desc>""");
svg.AppendLine("""  <defs><linearGradient id="field" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#071a2c"/><stop offset="1" stop-color="#030711"/></linearGradient><filter id="glow" x="-60%" y="-60%" width="220%" height="220%"><feGaussianBlur stdDeviation="4" result="blur"/><feMerge><feMergeNode in="blur"/><feMergeNode in="SourceGraphic"/></feMerge></filter></defs>""");
svg.AppendLine("""  <rect width="1000" height="360" rx="18" fill="url(#field)"/>""");
svg.AppendLine("""  <text x="36" y="38" fill="#f5f8ff" font-family="Segoe UI, sans-serif" font-size="20" font-weight="700">One entity identity. Different computational responsibilities.</text>""");
svg.AppendLine("""  <text x="36" y="61" fill="#9cb5ce" font-family="Segoe UI, sans-serif" font-size="12">Generated by running RendererComputationMachine → FSM_API → CurrentRepresentation</text>""");
svg.AppendLine("""  <path d="M110 142 H890" stroke="#46708d" stroke-width="2" stroke-dasharray="5 7" opacity=".8"/>""");

foreach (var item in results)
{
    var label = SecurityElement.Escape(item.Active.ToString()) ?? item.Active.ToString();
    var name = SecurityElement.Escape(item.Name) ?? item.Name;
    svg.AppendLine($"""  <g class="node node-{item.Active.ToString().ToLowerInvariant()}" transform="translate({item.X} 142)" role="img" aria-label="{name}: {label} representation">""");
    switch (item.Active)
    {
        case RepresentationTarget.Semantic:
            svg.AppendLine("""    <circle r="7" fill="#9ba9bc" stroke="#e0e8f4" stroke-width="1.5"/>""");
            break;
        case RepresentationTarget.Aggregate:
            svg.AppendLine("""    <circle r="15" fill="#1a4b61" stroke="#63d8f2" stroke-width="2"/><circle r="5" fill="#9be9ff"/>""");
            break;
        case RepresentationTarget.Distant:
            svg.AppendLine("""    <rect x="-13" y="-13" width="26" height="26" rx="4" fill="#174e89" stroke="#69aaff" stroke-width="2"/><path d="M-7 4 L0 -5 L7 4" fill="none" stroke="#d3e8ff" stroke-width="2"/>""");
            break;
        case RepresentationTarget.Near:
            svg.AppendLine("""    <path d="M0 -20 L-15 5 H-6 L-12 17 H12 L6 5 H15 Z" fill="#b77a24" stroke="#ffcf74" stroke-width="2"/><path d="M0 17 V24" stroke="#ffcf74" stroke-width="3"/>""");
            break;
        case RepresentationTarget.Interactive:
            svg.AppendLine("""    <circle class="pulse" r="27" fill="none" stroke="#ffe7a0" stroke-width="2"/><path d="M0 -22 L-17 5 H-7 L-13 18 H13 L7 5 H17 Z" fill="#e4ad34" stroke="#fff0b5" stroke-width="2.5" filter="url(#glow)"/><path d="M0 18 V25" stroke="#fff0b5" stroke-width="3"/>""");
            break;
    }
    svg.AppendLine($"""    <text x="0" y="48" text-anchor="middle" fill="#f5f8ff" font-family="Segoe UI, sans-serif" font-size="13" font-weight="700">{label}</text>""");
    svg.AppendLine($"""    <text x="0" y="67" text-anchor="middle" fill="#9cb5ce" font-family="Segoe UI, sans-serif" font-size="10">{name}</text>""");
    svg.AppendLine("  </g>");
}

svg.AppendLine("""  <path d="M36 292 H964" stroke="#27465f" stroke-width="1"/>""");
svg.AppendLine("""  <text x="36" y="315" fill="#b7cbe0" font-family="Segoe UI, sans-serif" font-size="12">State changes are real FSM_API transitions. Glow/pulse is SVG presentation only; this image is a generated snapshot, not a live process monitor.</text>""");
svg.AppendLine("""  <text x="36" y="337" fill="#6e91ad" font-family="Consolas, monospace" font-size="11">Rebuild: dotnet run --project samples/LivingRenderer -- docs/assets/living-event-horizons.svg</text>""");
svg.AppendLine("""  <style>@keyframes breathe{0%,100%{opacity:.45;transform:scale(.92)}50%{opacity:1;transform:scale(1.12)}}.pulse{transform-box:fill-box;transform-origin:center;animation:breathe 3s ease-in-out infinite}@media(prefers-reduced-motion:reduce){.pulse{animation:none;opacity:.8}}</style>""");
svg.AppendLine("</svg>");

Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
File.WriteAllText(outputPath, svg.ToString(), new UTF8Encoding(false));
Console.WriteLine($"Wrote {outputPath} from {results.Count} FSM_API-driven representation transitions.");
